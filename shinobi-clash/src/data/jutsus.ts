import type { JutsuDef } from '../core/types';

type JutsuInput = Omit<
  JutsuDef,
  'accuracy' | 'priority' | 'cooldown' | 'target' | 'effects' | 'tier' | 'animationId' | 'soundId'
> &
  Partial<JutsuDef>;

/** Valeurs par défaut d'un jutsu : une entrée de données suffit pour en ajouter un. */
function jutsu(input: JutsuInput): JutsuDef {
  return {
    accuracy: 100,
    priority: 0,
    cooldown: 0,
    target: 'foe',
    effects: [],
    tier: 0,
    animationId: input.basic ? 'strike' : 'blast',
    soundId: 'jutsu',
    ...input,
  };
}

